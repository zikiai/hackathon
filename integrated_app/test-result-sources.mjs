import assert from 'node:assert/strict';
const storage=new Map([['nx-result-ids',JSON.stringify({rail:['old-test']})],['nx-result-sources',JSON.stringify({rail:'uploaded'})]]);
globalThis.localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)};
const events=[];
globalThis.document={addEventListener(){},dispatchEvent:e=>events.push(e),getElementById:()=>null};
globalThis.CustomEvent=class{constructor(type,init){this.type=type;this.detail=init.detail;}};
globalThis.fetch=async url=>({ok:true,json:async()=>url.includes('test-result')?{csv:'file_id,ranked_cars\na.xlsx,01|02\n',cases:[{file_id:'a.xlsx'}]}:{csv:'file_id,prediction\nTest1.csv,Normal\n',records:[{id:'Test1.csv'}]}});
