await client.restoreResults();
assert.equal(client.hasUploadedResults('rail'),true);
assert.equal(client.resultSource('rail'),'official','Legacy one-file session must not hide official batch');
assert.equal(client.liveResult('rail'),undefined);
assert.equal(client.liveResult('acv').cases.length,1);
